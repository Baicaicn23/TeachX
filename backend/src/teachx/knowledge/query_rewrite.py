"""查询改写(学习版,P2 第一步)。

学习者的提问用口语(“一模一样”“表出来”),语料里是术语(“对称矩阵”
“线性组合”)——检索关键词对不上,这是召回不足的第一根因。本模块用一张
人工维护的同义词表把口语说法扩写成候选术语:扩展是**追加**(原查询保留,
术语 OR 进检索),不是替换,因此不会丢掉原始关键词的信息。

设计约束:
- 纯函数、确定性、零成本——检索评测(Mock 考卷)可以直接量化它的效果;
- 表按"模式 → 术语"组织,只收录口语和语料术语**确实对不上**的说法,
  不收录宽泛词(如"判断""怎么"),避免过度扩展稀释排序;
- LLM 改写是文档化的升级路径:接口保持 `expand_query(query) -> str`,
  未来可在 service 层按配置换成模型改写,评测方法不变。
"""

from __future__ import annotations

# 口语模式 → 语料术语。每条都在语义考卷的弱查询里有出处。
_LEARNER_SYNONYMS: tuple[tuple[str, tuple[str, ...]], ...] = (
    # “行列互换后和自己一模一样的矩阵” → 转置/对称矩阵
    ("行列互换", ("转置", "对称矩阵")),
    ("行列交换", ("转置", "对称矩阵")),
    ("一模一样", ("对称矩阵", "转置")),
    # “没有办法求出它的逆” → 行列式为零/不可逆
    ("没有办法求出它的逆", ("行列式为零", "不可逆")),
    ("求不出逆", ("行列式为零", "不可逆")),
    ("没有逆", ("行列式为零", "不可逆")),
    ("不可逆", ("行列式为零",)),
    # “彼此之间没法互相表出来” → 线性组合/线性相关/线性无关
    ("表出来", ("线性组合", "线性相关", "线性无关")),
    ("线性表出", ("线性组合", "线性无关")),
    # “能装多少内容,是由什么决定的” → 维数/基向量
    ("能装多少", ("维数", "基向量")),
    ("装多少内容", ("维数", "基向量")),
    # “方向没变的那些向量” → 特征值/特征向量
    ("方向没变", ("特征值", "特征向量")),
    ("方向不变", ("特征值", "特征向量")),
    # “先后作用的效果顺序不能随便调换” → 交换律
    ("调换顺序", ("交换律",)),
    ("先后作用", ("交换律", "交换")),
    # “长度会怎么变化” → 拉伸/压缩(特征值的几何意义)
    ("长度会怎么变化", ("拉伸", "压缩", "特征值")),
    ("拉伸或压缩", ("特征值",)),
)

# 单条查询最多追加的扩写术语数,防止极端情况下过度扩展稀释排序。
MAX_EXPANSION_TERMS = 8


def expansion_terms(query: str) -> list[str]:
    """返回查询命中的同义词术语(去重、限量、保持书写顺序)。"""

    text = str(query or "")
    terms: list[str] = []
    for pattern, synonyms in _LEARNER_SYNONYMS:
        if pattern in text:
            for term in synonyms:
                if term not in terms:
                    terms.append(term)
                if len(terms) >= MAX_EXPANSION_TERMS:
                    return terms
    return terms


def expand_query(query: str) -> str:
    """把同义词术语追加到原查询后面;没有命中时原样返回。"""

    terms = expansion_terms(query)
    if not terms:
        return str(query or "")
    return " ".join([str(query or "").strip(), *terms])


__all__ = ["MAX_EXPANSION_TERMS", "expand_query", "expansion_terms"]
